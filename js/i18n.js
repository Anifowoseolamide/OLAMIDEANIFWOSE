/**
 * Get current active locale (defaults to 'en')
 */
export function getCurrentLang() {
  const saved = localStorage.getItem('portfolio_lang');
  return (saved && TRANSLATIONS[saved]) ? saved : 'en';
}

/**
 * Helper to get translation object for active language
 */
export function getLangDict(langCode) {
  const code = langCode || getCurrentLang();
  return TRANSLATIONS[code] || TRANSLATIONS.en;
}
